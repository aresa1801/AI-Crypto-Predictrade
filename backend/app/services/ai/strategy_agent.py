    def get_active_signals(self) -> list[TradingSignal]:
        """Get all active (non-expired) signals"""
        now = datetime.now(timezone.utc)
        return [
            signal for signal in self._active_signals.values()
            if signal.valid_until > now
        ]
    
    def invalidate_signal(self, signal_id: str) -> bool:
        """Invalidate/remove an active signal"""
        if signal_id in self._active_signals:
            del self._active_signals[signal_id]
            return True
        return False
