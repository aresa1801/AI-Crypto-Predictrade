logger = logging.getLogger(__name__)


class SignalType(str, Enum):
    """Type of trading signal"""
    LONG = "long"
    SHORT = "short"
    HOLD = "hold"
    CLOSE_LONG = "close_long"
    CLOSE_SHORT = "close_short"


class SignalStrength(str, Enum):
    """Signal strength classification"""
    STRONG = "strong"
    MODERATE = "moderate"
    WEAK = "weak"


class MarketType(str, Enum):
    """Market type for signal - Platform supports spot trading only"""
    CEX_SPOT = "cex_spot"
    # CEX_FUTURES = "cex_futures"  # Not supported - spot trading only
    POLYMARKET = "polymarket"


@dataclass
class TradingSignal:
    """Trading signal generated by strategy agent"""
    signal_id: str
    timestamp: datetime
    
    # Signal details
    symbol: str
    market_type: MarketType
    signal_type: SignalType
    strength: SignalStrength
    
    # Confidence and reasoning
    confidence: float  # 0-1
    reasoning: str
    
    # Price targets
    entry_price: Decimal
    stop_loss: Decimal
    take_profit: Decimal
    
    # Position sizing suggestion
    suggested_position_pct: float
    risk_reward_ratio: float
    
    # Time validity
    valid_until: datetime
    
    # Additional data
    indicators_snapshot: dict = field(default_factory=dict)
    market_context: dict = field(default_factory=dict)
    
    def to_dict(self) -> dict:
        return {
            "signal_id": self.signal_id,
            "timestamp": self.timestamp.isoformat(),
            "symbol": self.symbol,
            "market_type": self.market_type.value,
            "signal_type": self.signal_type.value,
            "strength": self.strength.value,
            "confidence": self.confidence,
            "reasoning": self.reasoning,
            "entry_price": float(self.entry_price),
            "stop_loss": float(self.stop_loss),
            "take_profit": float(self.take_profit),
            "suggested_position_pct": self.suggested_position_pct,
            "risk_reward_ratio": self.risk_reward_ratio,
            "valid_until": self.valid_until.isoformat(),
            "indicators_snapshot": self.indicators_snapshot,
            "market_context": self.market_context
        }


